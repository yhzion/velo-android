package io.github.yhzion.velo.updates

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

class ChangeNotesTest {
    private fun block(vararg lines: String) =
        (listOf("<!-- velo-changes -->") + lines + "<!-- /velo-changes -->").joinToString("\n")

    @Test fun readsSectionsBetweenTheMarkersOnly() {
        val body = listOf(
            "<!-- android-version-code: 3000038 -->",
            "- Not inside the block.",
            block("### Added", "- A dot on Settings tells you when an update is ready.",
                "### Fixed", "- Hangul no longer looks flat in D2Coding."),
            "",
            "## What's Changed",
            "### Added",
            "- Generated by GitHub, outside the block.",
        ).joinToString("\r\n")
        assertEquals(listOf(
            ChangeSection(ChangeKind.Added, listOf("A dot on Settings tells you when an update is ready.")),
            ChangeSection(ChangeKind.Fixed, listOf("Hangul no longer looks flat in D2Coding.")),
        ), changeNotes(body))
    }

    @Test fun sectionsFollowTheirFixedOrderAndUnknownOnesAreIgnored() {
        val body = block(
            "### Security", "- Pinned the release host.",
            "### Deprecated", "- Not a section the app shows.",
            "- Still under the unknown heading.",
            "### Removed", "- Dropped the legacy theme.",
            "### Changed", "- Velo checks for updates automatically.",
            "### Added", "- What's new on the Updates page.",
            "### Fixed", "- One.", "### Fixed", "- Two.",
        )
        val sections = changeNotes(body)
        assertEquals(ChangeKind.entries, sections.map { it.kind })
        assertEquals(listOf("One.", "Two."), sections.single { it.kind == ChangeKind.Fixed }.items)
        assertEquals("New", ChangeKind.Added.title)
    }

    @Test fun ignoresOtherLinesAndItemsBeforeAnyHeading() {
        val body = block(
            "- Before a heading.", "Some prose.", "### Added", "", "  - Indented is not an item.", "* Not a dash item.",
            "-No space.", "- ", "-   Spaced item.   ", "<!-- velo-changes -->", "#### Added", "- Kept under Added.",
        )
        assertEquals(listOf(ChangeSection(ChangeKind.Added, listOf("Spaced item.", "Kept under Added."))), changeNotes(body))
    }

    @Test fun linksBecomeTheirText() {
        val body = block("### Fixed",
            "- Fixed [#12](https://github.com/yhzion/velo-android/issues/12) and [the font](https://example.com/a(b)).",
            "- ![logo](https://example.com/x.png) shows its alt text, [] (not a link) stays.")
        assertEquals(listOf(
            "Fixed #12 and the font.",
            "logo shows its alt text, [] (not a link) stays.",
        ), changeNotes(body).single().items)
    }

    @Test fun keepsAtMostTwelveItemsAndTruncatesLongOnes() {
        val many = (1..9).map { "- Added $it." } + "### Fixed" + (1..9).map { "- Fixed $it." }
        val sections = changeNotes(block("### Added", *many.toTypedArray()))
        assertEquals(12, sections.sumOf { it.items.size })
        assertEquals(9, sections.first { it.kind == ChangeKind.Added }.items.size)
        assertEquals(listOf("Fixed 1.", "Fixed 2.", "Fixed 3."), sections.first { it.kind == ChangeKind.Fixed }.items)

        val long = changeNotes(block("### Changed", "- " + "x".repeat(500))).single().items.single()
        assertEquals(200, long.length)
        assertTrue(long.endsWith("…"))
        val exact = "y".repeat(200)
        assertEquals(exact, changeNotes(block("### Changed", "- $exact")).single().items.single())
        // A cut never splits a surrogate pair.
        val emoji = changeNotes(block("### Changed", "- " + "z".repeat(198) + "😀".repeat(5))).single().items.single()
        assertEquals("z".repeat(198) + "…", emoji)
    }

    @Test fun noBlockOrAnUnclosedBlockMeansNoList() {
        assertEquals(emptyList<ChangeSection>(), changeNotes(""))
        assertEquals(emptyList<ChangeSection>(), changeNotes("<!-- android-version-code: 3000037 -->\n## What's Changed\n### Added\n- x"))
        assertEquals(emptyList<ChangeSection>(), changeNotes("<!-- velo-changes -->\n### Added\n- Never closed."))
        assertEquals(emptyList<ChangeSection>(), changeNotes("<!-- /velo-changes -->\n### Added\n- x\n<!-- velo-changes -->"))
        assertEquals(emptyList<ChangeSection>(), changeNotes(block("### Added")))
        assertEquals(emptyList<ChangeSection>(), changeNotes("quoted <!-- velo-changes -->\n### Added\n- x\n<!-- /velo-changes -->"))
    }
}
